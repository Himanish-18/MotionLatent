"""
PCA-32 Standalone Exporter & C Header Generator -- Phase 4.

Exports the frozen PCA-32 dimensionality reduction transform to:
1. C Header (`pca32_params.h`) with static const float arrays.
2. Raw binary blobs (`pca32_mean.bin`, `pca32_components.bin`).
3. Deterministic test fixture (`pca32_test_fixture.json`) for C vs. Python parity tests.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Any, Optional, Tuple
import numpy as np

from src.data.loso import load_fold_data
from src.models.pca_model import PCARepresentation


def export_pca32_c_header(
    mean: np.ndarray,
    components: np.ndarray,
    output_header_path: Path,
) -> None:
    """Generate C header file embedding PCA-32 parameters as static const arrays."""
    assert mean.shape == (6912,), f"Expected mean shape (6912,), got {mean.shape}"
    assert components.shape == (32, 6912), f"Expected components shape (32, 6912), got {components.shape}"

    output_header_path = Path(output_header_path)
    output_header_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_header_path, "w", encoding="utf-8") as f:
        f.write("/**\n")
        f.write(" * @file pca32_params.h\n")
        f.write(" * @brief Autogenerated static parameters for PCA-32 embedded inference.\n")
        f.write(" * Total ROM size: (6912 + 32 * 6912) * 4 bytes = 912,384 bytes (~891 KB).\n")
        f.write(" */\n\n")
        f.write("#ifndef MOTIONLATENT_PCA32_PARAMS_H\n")
        f.write("#define MOTIONLATENT_PCA32_PARAMS_H\n\n")
        f.write("#define PCA32_STATIC_PARAMS_AVAILABLE 1\n\n")

        # Write Mean vector
        f.write("static const float PCA32_MEAN[6912] = {\n")
        for i in range(0, 6912, 8):
            chunk = ", ".join(f"{v:.8e}f" for v in mean[i:i+8])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")

        # Write Components matrix
        f.write("static const float PCA32_COMPONENTS[32][6912] = {\n")
        for d in range(32):
            f.write(f"    /* Component {d} */\n    {{\n")
            for i in range(0, 6912, 8):
                chunk = ", ".join(f"{v:.8e}f" for v in components[d, i:i+8])
                f.write(f"        {chunk},\n")
            f.write("    },\n")
        f.write("};\n\n")

        f.write("#endif /* MOTIONLATENT_PCA32_PARAMS_H */\n")


def export_pca32_artifacts(
    fold_subject: int = 101,
    output_dir: Optional[Path] = None,
) -> Dict[str, Path]:
    """Fit PCA-32 on fold training subjects, export C header, binaries, and test fixture."""
    if output_dir is None:
        output_dir = Path(__file__).resolve().parent
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # 1. Load Fold Data (Fold S101 is the standard primary evaluation fold)
    fold = load_fold_data(test_subject=fold_subject, pure_only=True, exclude_transient=True)
    pca = PCARepresentation(max_components=32, random_state=42).fit(fold.X_train)

    mean = pca.mean_.astype(np.float32)
    components = pca.components_[:32].astype(np.float32)

    # 2. Export C header
    header_path = output_dir / "pca32_params.h"
    export_pca32_c_header(mean, components, header_path)

    # 3. Export binary files
    bin_mean_path = output_dir / "pca32_mean.bin"
    bin_comp_path = output_dir / "pca32_components.bin"
    mean.tofile(bin_mean_path)
    components.tofile(bin_comp_path)

    # 4. Generate deterministic test fixture from 10 test windows
    test_windows = fold.X_test[:10].astype(np.float32)
    py_latents = pca.transform(test_windows, d=32)

    fixture_path = output_dir / "pca32_test_fixture.json"
    fixture_data = {
        "test_subject": fold_subject,
        "n_samples": len(test_windows),
        "input_dim": 6912,
        "latent_dim": 32,
        "inputs": test_windows.tolist(),
        "expected_latents": py_latents.tolist(),
    }
    with open(fixture_path, "w", encoding="utf-8") as f:
        json.dump(fixture_data, f, indent=2)

    return {
        "header": header_path,
        "bin_mean": bin_mean_path,
        "bin_comp": bin_comp_path,
        "fixture": fixture_path,
    }


if __name__ == "__main__":
    paths = export_pca32_artifacts()
    print("PCA-32 Artifacts exported successfully:")
    for k, p in paths.items():
        print(f"  {k}: {p} ({p.stat().st_size / 1024:.1f} KB)")
